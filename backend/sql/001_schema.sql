CREATE OR REPLACE VIEW V_CLUSTER_BOARD AS
SELECT
    c.CLUSTER_ID,
    c.CLUSTER_KEY,
    c.LABEL,
    c.GROUND,
    c.PRODUCT,
    c.WOW_GROWTH,
    c.FIRST_SEEN,
    c.STATUS,
    c.SUMMARY,
    COUNT(cm.TICKET_ID) AS SIZE,
    COUNT(DISTINCT t.BRANCH_ID) AS BRANCH_COUNT,
    COALESCE(AVG(cm.ASSIGNMENT_CONFIDENCE), 0) AS CONFIDENCE
FROM CLUSTERS c
LEFT JOIN CLUSTER_MEMBERSHIPS cm ON cm.CLUSTER_ID = c.CLUSTER_ID
LEFT JOIN TICKETS t ON t.TICKET_ID = cm.TICKET_ID
WHERE c.RETIRED_AT IS NULL
GROUP BY c.CLUSTER_ID, c.CLUSTER_KEY, c.LABEL, c.GROUND, c.PRODUCT,
         c.WOW_GROWTH, c.FIRST_SEEN, c.STATUS, c.SUMMARY;

CREATE OR REPLACE VIEW V_REVIEW_QUEUE AS
SELECT
    t.TICKET_ID,
    t.SOURCE_TICKET_ID,
    t.RECEIVED_AT,
    t.CHANNEL,
    t.BRANCH_ID,
    t.PRODUCT,
    t.AGENT_TYPE,
    SUBSTR(REGEXP_REPLACE(t.RAW_TEXT, '\\b[0-9]{10,16}\\b', 'REDACTED'), 1, 260) AS EXCERPT,
    i.CONFIDENCE,
    i.TRIGGER_PHRASE,
    i.GROUND_PRED,
    i.MODEL_VERSION,
    i.PROCESSED_AT
FROM TICKETS t
JOIN TICKET_INSIGHTS i ON i.TICKET_ID = t.TICKET_ID
WHERE t.AGENT_TYPE IN ('query', 'request') AND i.IS_COMPLAINT_PRED = TRUE;

CREATE OR REPLACE VIEW V_PIPELINE_STATUS AS
SELECT
    (SELECT COUNT(*) FROM TICKETS) AS TICKETS_TOTAL,
    (SELECT COUNT(*) FROM TICKET_INSIGHTS) AS TICKETS_SCORED,
    (SELECT COUNT(*) FROM REVIEW_EVENTS) AS REVIEWS_RECORDED,
    (SELECT MODEL_VERSION FROM MODEL_VERSIONS WHERE STATUS='active' LIMIT 1) AS ACTIVE_MODEL,
    (SELECT MAX(FINISHED_AT) FROM PIPELINE_RUNS WHERE STATUS='succeeded') AS LAST_SUCCESSFUL_RUN,
    (SELECT COUNT(*) FROM PIPELINE_RUNS WHERE STATUS='failed') AS FAILED_RUNS;
