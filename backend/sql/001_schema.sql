-- Run as a user allowed to create objects in COMPLAINT_ENGINE.
CREATE SCHEMA IF NOT EXISTS COMPLAINT_ENGINE;
OPEN SCHEMA COMPLAINT_ENGINE;

CREATE TABLE IF NOT EXISTS TICKETS (
    TICKET_ID VARCHAR(36) PRIMARY KEY,
    SOURCE_SYSTEM VARCHAR(80) NOT NULL,
    SOURCE_TICKET_ID VARCHAR(120) NOT NULL,
    RECEIVED_AT TIMESTAMP NOT NULL,
    CHANNEL VARCHAR(40) NOT NULL,
    BRANCH_ID VARCHAR(40) NOT NULL,
    PRODUCT VARCHAR(80) NOT NULL,
    AGENT_CATEGORY VARCHAR(120) NOT NULL,
    AGENT_TYPE VARCHAR(20) NOT NULL,
    RESOLUTION VARCHAR(240),
    ESCALATED_TO_IO BOOLEAN NOT NULL,
    RAW_TEXT VARCHAR(20000) UTF8 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT UQ_TICKET_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TICKET_ID)
);

CREATE TABLE IF NOT EXISTS MODEL_VERSIONS (
    MODEL_VERSION VARCHAR(80) PRIMARY KEY,
    MODEL_TYPE VARCHAR(60) NOT NULL,
    ARTIFACT_URI VARCHAR(500),
    TRAINING_DATA_HASH VARCHAR(128),
    THRESHOLD DOUBLE NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    ACTIVATED_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TICKET_INSIGHTS (
    TICKET_ID VARCHAR(36) PRIMARY KEY REFERENCES TICKETS(TICKET_ID),
    IS_COMPLAINT_PRED BOOLEAN NOT NULL,
    CONFIDENCE DOUBLE NOT NULL,
    TRIGGER_PHRASE VARCHAR(240) UTF8 NOT NULL,
    GROUND_PRED VARCHAR(160) UTF8 NOT NULL,
    CLUSTER_KEY VARCHAR(80),
    AMOUNT DECIMAL(18,2),
    TRANSACTION_REFERENCE VARCHAR(100),
    EXPLANATION_TYPE VARCHAR(60) NOT NULL,
    MODEL_VERSION VARCHAR(80) NOT NULL REFERENCES MODEL_VERSIONS(MODEL_VERSION),
    PROCESSED_AT TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS CLUSTERS (
    CLUSTER_ID VARCHAR(36) PRIMARY KEY,
    CLUSTER_KEY VARCHAR(80) NOT NULL,
    LABEL VARCHAR(240) UTF8 NOT NULL,
    GROUND VARCHAR(160) UTF8 NOT NULL,
    PRODUCT VARCHAR(80) NOT NULL,
    WOW_GROWTH DOUBLE NOT NULL,
    FIRST_SEEN DATE NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    SUMMARY VARCHAR(2000) UTF8 NOT NULL,
    DISCOVERY_MODEL_VERSION VARCHAR(80) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    RETIRED_AT TIMESTAMP,
    CONSTRAINT UQ_CLUSTER_KEY UNIQUE (CLUSTER_KEY)
);

CREATE TABLE IF NOT EXISTS CLUSTER_MEMBERSHIPS (
    TICKET_ID VARCHAR(36) NOT NULL REFERENCES TICKETS(TICKET_ID),
    CLUSTER_ID VARCHAR(36) NOT NULL REFERENCES CLUSTERS(CLUSTER_ID),
    ASSIGNMENT_CONFIDENCE DOUBLE NOT NULL,
    ASSIGNMENT_METHOD VARCHAR(40) NOT NULL,
    MODEL_VERSION VARCHAR(80) NOT NULL,
    ASSIGNED_AT TIMESTAMP NOT NULL,
    PRIMARY KEY (TICKET_ID, CLUSTER_ID)
);

CREATE TABLE IF NOT EXISTS REVIEW_EVENTS (
    REVIEW_ID VARCHAR(36) PRIMARY KEY,
    TICKET_ID VARCHAR(36) NOT NULL REFERENCES TICKETS(TICKET_ID),
    ACTOR_ID VARCHAR(160) NOT NULL,
    DECISION VARCHAR(20) NOT NULL,
    REASON VARCHAR(1000) UTF8,
    CORRECTED_TYPE VARCHAR(20),
    CORRECTED_GROUND VARCHAR(160) UTF8,
    PREVIOUS_PREDICTION VARCHAR(4000) UTF8 NOT NULL,
    MODEL_VERSION VARCHAR(80) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS PIPELINE_RUNS (
    RUN_ID VARCHAR(36) PRIMARY KEY,
    RUN_TYPE VARCHAR(40) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    FINISHED_AT TIMESTAMP,
    PROCESSED_COUNT DECIMAL(18,0) NOT NULL,
    ERROR_MESSAGE VARCHAR(2000) UTF8
);

CREATE TABLE IF NOT EXISTS IMPORTS (
    IMPORT_ID VARCHAR(36) PRIMARY KEY,
    FILENAME VARCHAR(240) UTF8 NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    ACCEPTED DECIMAL(18,0) NOT NULL,
    ERRORS_JSON VARCHAR(2000000) UTF8 NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL
);

